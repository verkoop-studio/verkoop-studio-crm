/*
 * Put an export back, into a database we own.
 *
 *   node scripts/import-everything.mjs export/2026-11-14-09-30-00
 *
 * It writes `import.sql` next to the export and uploads the stored files, then
 * prints the one psql command to run. It does not run psql itself: loading a
 * company's whole history into a database is a thing to do on purpose, with
 * the statements in front of you.
 *
 * Why SQL and not the API
 * -----------------------
 * Primary keys. `leads.owner_id`, `profiles.id` and `user_roles.user_id` all
 * point at `auth.users(id)`. Re-creating accounts through the Auth admin API
 * gives them new ids, and every one of those links would then point at nobody:
 * leads with no owner, nobody with a role, a CRM that loads and is empty. Going
 * in through Postgres keeps every id exactly as it was.
 *
 * Passwords
 * ---------
 * The export has none — no API hands them out. Each account is written with no
 * usable password, so the first thing everyone does on the new stack is "forgot
 * my password". That is the whole cost of the move, and it is a one-off.
 *
 * Foreign keys
 * ------------
 * The load runs with `session_replication_role = replica`, which turns off
 * foreign key and trigger checking for the session. The export came out of a
 * database that enforced all of it, so the rows are consistent by construction;
 * what this avoids is having to guess the one insert order that satisfies every
 * constraint, and failing halfway through a restore.
 */

import { readFileSync, writeFileSync, readdirSync, statSync, existsSync } from "node:fs";
import { join, relative, sep } from "node:path";

const root = process.argv[2];
if (!root || !existsSync(join(root, "manifest.json"))) {
  console.error("Point this at an export directory, the one holding manifest.json.");
  process.exit(1);
}

const manifest = JSON.parse(readFileSync(join(root, "manifest.json"), "utf8"));

// The order the export wrote them in. Replica mode means it does not have to be
// the order the foreign keys want, but accounts first still reads better in a
// file someone may have to look through at four in the morning.
const TABLES = [
  "companies",
  "profiles",
  "user_roles",
  "import_batches",
  "leads",
  "activities",
  "company_invitations",
  "account_requests",
  "app_settings",
  "teamleader_contacts",
];

const quote = (value) => {
  if (value === null || value === undefined) return "NULL";
  if (typeof value === "number") return Number.isFinite(value) ? String(value) : "NULL";
  if (typeof value === "boolean") return value ? "true" : "false";
  const text = typeof value === "object" ? JSON.stringify(value) : String(value);
  return `'${text.replace(/'/g, "''")}'`;
};

const lines = [
  "-- Generated by scripts/import-everything.mjs. Read before running.",
  `-- From ${manifest.project}, taken ${manifest.takenAt}.`,
  "",
  "BEGIN;",
  "SET session_replication_role = replica;",
  "",
];

/* Accounts, with their ids and their confirmations, and no password. */
const users = JSON.parse(readFileSync(join(root, "auth/users.json"), "utf8"));
lines.push(`-- ${users.length} accounts. No passwords: everyone resets once.`);
for (const user of users) {
  lines.push(
    `INSERT INTO auth.users (instance_id, id, aud, role, email, encrypted_password,` +
      ` email_confirmed_at, raw_app_meta_data, raw_user_meta_data, created_at, updated_at,` +
      ` last_sign_in_at, confirmation_sent_at)` +
      ` VALUES ('00000000-0000-0000-0000-000000000000', ${quote(user.id)}, 'authenticated',` +
      ` ${quote(user.role ?? "authenticated")}, ${quote(user.email)}, '',` +
      ` ${quote(user.email_confirmed_at)}, ${quote(user.app_metadata ?? {})},` +
      ` ${quote(user.user_metadata ?? {})}, ${quote(user.created_at)}, ${quote(user.updated_at)},` +
      ` ${quote(user.last_sign_in_at)}, ${quote(user.confirmation_sent_at)})` +
      ` ON CONFLICT (id) DO NOTHING;`,
  );
  // Without an identity row GoTrue will not let the address sign in at all, and
  // "forgot my password" on an account it cannot find is a dead end.
  lines.push(
    `INSERT INTO auth.identities (provider_id, user_id, identity_data, provider, created_at, updated_at)` +
      ` VALUES (${quote(user.id)}, ${quote(user.id)},` +
      ` ${quote({ sub: user.id, email: user.email, email_verified: Boolean(user.email_confirmed_at) })},` +
      ` 'email', ${quote(user.created_at)}, ${quote(user.updated_at)})` +
      ` ON CONFLICT (provider_id, provider) DO NOTHING;`,
  );
}
lines.push("");

let rowTotal = 0;
for (const table of TABLES) {
  const path = join(root, "tables", `${table}.json`);
  if (!existsSync(path)) continue;
  const rows = JSON.parse(readFileSync(path, "utf8"));
  lines.push(`-- ${table}: ${rows.length} rows`);
  for (const row of rows) {
    const columns = Object.keys(row);
    lines.push(
      `INSERT INTO public.${table} (${columns.map((c) => `"${c}"`).join(", ")})` +
        ` VALUES (${columns.map((c) => quote(row[c])).join(", ")}) ON CONFLICT DO NOTHING;`,
    );
  }
  rowTotal += rows.length;
  lines.push("");
}

/* The buckets themselves, before anything is put in them. */
for (const bucket of Object.keys(manifest.storage ?? {})) {
  lines.push(
    `INSERT INTO storage.buckets (id, name, public) VALUES (${quote(bucket)}, ${quote(bucket)}, false)` +
      ` ON CONFLICT (id) DO NOTHING;`,
  );
}

lines.push("", "SET session_replication_role = DEFAULT;", "COMMIT;", "");

const sqlPath = join(root, "import.sql");
writeFileSync(sqlPath, lines.join("\n"));

/* The files. These go through the storage API rather than the database,
   because the bytes live outside Postgres and the object rows are written by
   the service that owns them. */
const BASE = (process.env["TARGET_SUPABASE_URL"] ?? "").replace(/\/+$/, "");
const KEY = process.env["TARGET_SERVICE_ROLE_KEY"] ?? "";

/*
 * Storage refuses a body with no content type, and answers 415 rather than
 * guessing. The CRM accepts PDF, Word, PNG and JPEG and nothing else, so the
 * list is short; anything unexpected goes up as a plain download rather than
 * not going up at all.
 */
const MIME = {
  pdf: "application/pdf",
  png: "image/png",
  jpg: "image/jpeg",
  jpeg: "image/jpeg",
  doc: "application/msword",
  docx: "application/vnd.openxmlformats-officedocument.wordprocessingml.document",
};
const mimeFor = (path) =>
  MIME[path.split(".").pop()?.toLowerCase() ?? ""] ?? "application/octet-stream";

const walk = (dir) =>
  readdirSync(dir).flatMap((entry) => {
    const path = join(dir, entry);
    return statSync(path).isDirectory() ? walk(path) : [path];
  });

let uploaded = 0;
let files = 0;
for (const bucket of Object.keys(manifest.storage ?? {})) {
  const dir = join(root, "storage", bucket);
  if (!existsSync(dir)) continue;
  const paths = walk(dir);
  files += paths.length;
  if (!BASE || !KEY) continue;
  // Make the bucket through the API rather than relying on import.sql having
  // been run first: the two halves of this script should not have an order.
  await fetch(`${BASE}/storage/v1/bucket`, {
    method: "POST",
    headers: { apikey: KEY, Authorization: `Bearer ${KEY}`, "Content-Type": "application/json" },
    body: JSON.stringify({ id: bucket, name: bucket, public: false }),
  }).catch(() => {});
  for (const path of paths) {
    const key = relative(dir, path).split(sep).join("/");
    const response = await fetch(`${BASE}/storage/v1/object/${bucket}/${encodeURI(key)}`, {
      method: "POST",
      headers: {
        apikey: KEY,
        Authorization: `Bearer ${KEY}`,
        "Content-Type": mimeFor(key),
        "x-upsert": "true",
      },
      body: readFileSync(path),
    });
    if (!response.ok && response.status !== 409) {
      console.error(`! ${bucket}/${key} answered ${response.status}`);
      continue;
    }
    uploaded += 1;
  }
}

console.log(`Wrote ${sqlPath}`);
console.log(`  ${users.length} accounts, ${rowTotal} rows across ${TABLES.length} tables.`);
if (BASE && KEY) console.log(`  ${uploaded} of ${files} stored files uploaded.`);
else
  console.log(
    `  ${files} stored files NOT uploaded: set TARGET_SUPABASE_URL and TARGET_SERVICE_ROLE_KEY and run again.`,
  );
console.log(
  `\nRead it, then load it:\n  psql "$TARGET_DATABASE_URL" -v ON_ERROR_STOP=1 -f ${sqlPath}`,
);
console.log(
  "\nEveryone signs in with 'forgot my password' afterwards. The export holds no passwords.",
);
